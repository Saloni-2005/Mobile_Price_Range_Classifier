"""
GET /explain/{prediction_id} — local TreeSHAP attribution endpoint (PRD Ch. 11, 14, 17).

Decomposes a past prediction into feature-level Shapley values relative to the base value.
"""

from __future__ import annotations

from fastapi import APIRouter, Depends, HTTPException, Path
from sqlalchemy.orm import Session

from app.auth.jwt_handler import require_analyst_jwt
from app.db.models import ModelRegistry, Prediction
from app.db.session import SessionLocal, init_db
from app.schemas.prediction import ExplainResponse
from app.services.inference import get_active_model_version
from app.services.shap_service import explain_prediction

router = APIRouter(tags=["explain"])


def get_db():
    init_db()
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()


@router.get("/explain/{prediction_id}", response_model=ExplainResponse, status_code=200)
def explain(
    prediction_id: int = Path(..., ge=1, description="Unique prediction row ID"),
    db: Session = Depends(get_db),
    _claims: dict = Depends(require_analyst_jwt),
) -> ExplainResponse:
    """
    Retrieve TreeSHAP local feature attributions for a logged prediction.

    Returns:
    - 200: Base value, predicted probability, and sorted feature attributions.
    - 404: If prediction_id is not found.
    - 409: If prediction was generated by a superseded model version.
    """
    # 1. Fetch prediction record
    pred = db.query(Prediction).filter(Prediction.id == prediction_id).first()
    if pred is None:
        raise HTTPException(
            status_code=404,
            detail=f"Prediction #{prediction_id} not found.",
        )

    # 2. Check model version compatibility (PRD Chapter 17 / 19)
    active_reg = (
        db.query(ModelRegistry).filter(ModelRegistry.is_active.is_(True)).first()
    )
    if active_reg and pred.model_version_id != active_reg.id:
        pred_version_tag = (
            pred.model_version.version_tag
            if pred.model_version
            else f"ID:{pred.model_version_id}"
        )
        raise HTTPException(
            status_code=409,
            detail=(
                f"Prediction #{prediction_id} was generated with model version '{pred_version_tag}', "
                f"which has been superseded by active model version '{active_reg.version_tag}'."
            ),
        )

    # 3. Compute TreeSHAP attributions
    try:
        result = explain_prediction(
            input_specs=pred.input_json,
            target_class=pred.predicted_tier,
        )
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Failed to compute TreeSHAP explanation: {exc}",
        ) from exc

    current_version = active_reg.version_tag if active_reg else get_active_model_version()

    return ExplainResponse(
        prediction_id=pred.id,
        predicted_tier=result["target_class"],
        tier_label=result["tier_label"],
        base_value=result["base_value"],
        predicted_probability=result["predicted_probability"],
        attributions=result["attributions"],
        model_version=current_version,
    )
